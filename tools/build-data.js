#!/usr/bin/env node
/* Transform the Bowserinator PeriodicTableJSON into a trimmed, app-ready
 * window.ELEMENTS array written to Data/elements.js. Run: npm run build-data */
const fs = require('fs');
const path = require('path');

const raw = require('../Data/elements-raw.json').elements;

// Normalise the messy "unknown, probably X" categories down to a base family.
function normCategory(cat) {
  if (!cat) return 'unknown';
  const c = cat.toLowerCase();
  if (c.includes('alkali metal') && !c.includes('alkaline')) return 'alkali metal';
  if (c.includes('alkaline earth')) return 'alkaline earth metal';
  if (c.includes('transition metal') && c.includes('post')) return 'post-transition metal';
  if (c.includes('transition metal')) return 'transition metal';
  if (c.includes('post-transition')) return 'post-transition metal';
  if (c.includes('metalloid')) return 'metalloid';
  if (c.includes('noble gas')) return 'noble gas';
  if (c.includes('lanthanide')) return 'lanthanide';
  if (c.includes('actinide')) return 'actinide';
  if (c.includes('diatomic')) return 'diatomic nonmetal';
  if (c.includes('polyatomic')) return 'polyatomic nonmetal';
  if (c.includes('nonmetal')) return 'polyatomic nonmetal';
  return 'unknown';
}

const out = raw
  .filter(e => typeof e.number === 'number' && e.number >= 1 && e.number <= 118)
  .map(e => ({
    number: e.number,
    symbol: e.symbol,
    name: e.name,
    mass: e.atomic_mass != null ? Math.round(e.atomic_mass * 1000) / 1000 : null,
    category: normCategory(e.category),
    rawCategory: e.category,
    phase: e.phase || null,            // phase at 0°C / STP-ish
    melt: e.melt,                      // Kelvin
    boil: e.boil,                      // Kelvin
    density: e.density,                // g/cm3 (or g/L for gases)
    molarHeat: e.molar_heat,
    electronegativity: e.electronegativity_pauling,
    electronAffinity: e.electron_affinity,
    ionization: Array.isArray(e.ionization_energies) ? e.ionization_energies[0] : null,
    shells: e.shells,                  // e.g. [2,8,1]
    config: e.electron_configuration,
    configSemantic: e.electron_configuration_semantic,
    block: e.block,
    period: e.period,
    group: e.group,
    xpos: e.xpos,
    ypos: e.ypos,
    appearance: e.appearance,
    summary: cleanSummary(e.summary),
    discoveredBy: e.discovered_by,
    namedBy: e.named_by,
    color: e['cpk-hex'] ? '#' + e['cpk-hex'] : null,
    image: e.image ? { url: e.image.url, title: e.image.title, attribution: e.image.attribution } : null,
    spectral: e.spectral_img || null,
    source: e.source || null,
  }));

function cleanSummary(s) {
  if (!s) return '';
  // Drop the IPA pronunciation noise that clutters several summaries.
  return s.replace(/\s*\/[^/]+\/\s*/g, ' ').replace(/\s{2,}/g, ' ').trim();
}

const header = '/* Auto-generated by tools/build-data.js from Bowserinator/Periodic-Table-JSON (public domain).\n' +
  ' * Do not edit by hand — re-run the build script instead. */\n';
const js = header + 'window.ELEMENTS = ' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'Data', 'elements.js'), js);
console.log('Wrote Data/elements.js with', out.length, 'elements (', js.length, 'bytes )');
